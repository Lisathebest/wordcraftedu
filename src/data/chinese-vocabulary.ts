import type { ChineseLevel, ChineseVocabularyWord } from "@/types/chinese-learning";

type WordSpec = [word: string, chinese: string, verbs: string[]];

function makeLevel(level: ChineseLevel, specs: WordSpec[]): ChineseVocabularyWord[] {
  return specs.map(([word, chinese, verbs]) => ({
    id: `zh-${word}`,
    word,
    chinese,
    level,
    image: `/vocab-zh/l${level}/${word}.png`,
    verbs,
  }));
}

